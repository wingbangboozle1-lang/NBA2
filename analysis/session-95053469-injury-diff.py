"""INJ-3: consecutive-report diff over every archived official injury PDF.

Input : data/raw/pdf/Injury-Report_<date>_<hh>_<mm><AM|PM>.pdf  (committed official bytes)
        and its .txt extraction (regenerated by nba2.pipeline.refresh.pdf_text, INJ-2).
Method: player-status pairs via the narrowed PLAYER_STATUS_RE defined below (see comment),
        keyed on (game date, player). Game date = the nearest MM/DD/YYYY token before the row
        (the flattened text prints the date once per date group). Only game dates present in
        BOTH releases are compared; other rows are counted, not diffed. Consecutive releases are ordered by the stamp in the filename.
Output: analysis/session-95053469-injury-diff.json
Limits: key = player name only; reasons are not diffed; rows with blank status are not
        counted (see coverage field).
"""
import glob, json, os, re, sys, hashlib, unicodedata
from datetime import datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from nba2.pipeline.refresh import pdf_text

# Player-status token. The committed PLAYER_STATUS_RE (nba2/pipeline/refresh.py) is too loose for
# keying: its name group swallows the preceding reason/team text ("Illness - Left Foot Fracture
# Landale, Jock"). This pattern takes only the surname (plus Jr./Sr./II-IV suffix) and first name
# that immediately precede the status word.
PLAYER_STATUS_RE = re.compile(
    r"(?<![A-Za-z])((?:(?:de|da|del|van|von|di|le) )?[A-Z][A-Za-z'.\-]*"
    r"(?:, (?:Jr\.|Sr\.|II|III|IV))?(?: (?:Jr\.|Sr\.|II|III|IV))?), "
    r"([A-Z][A-Za-z'.\-]*(?: [A-Z][A-Za-z'.\-]*)?)"
    r"\s+(NOT YET SUBMITTED|Out|Doubtful|Questionable|Probable|Available)\b")

PDF_DIR = os.path.join(ROOT, "data/raw/pdf")
DATE_RE = re.compile(r"\b(\d{2}/\d{2}/\d{4})\b")
RE = re.compile(r"Injury-Report_(\d{4})-(\d{2})-(\d{2})_(\d{2})_(\d{2})(AM|PM)\.pdf$")

def stamp(fn):
    m = RE.search(fn)
    y, mo, d, hh, mm, ap = m.groups()
    h = int(hh) % 12 + (12 if ap == "PM" else 0)
    return datetime(int(y), int(mo), int(d), h, int(mm))

releases = []
for p in glob.glob(os.path.join(PDF_DIR, "*.pdf")):
    fn = os.path.basename(p)
    blob = open(p, "rb").read()
    text = pdf_text(blob)  # committed extractor, run on committed bytes
    norm = unicodedata.normalize("NFKC", text)
    # game date of each row = the most recent MM/DD/YYYY token before it in the text
    dates = [(m.start(), m.group(0)) for m in DATE_RE.finditer(norm)]
    rows = {}
    for m in PLAYER_STATUS_RE.finditer(norm):
        name = f"{m.group(1)}, {m.group(2)}"
        if len(name) < 4:
            continue
        before = [d for pos, d in dates if pos < m.start()]
        gdate = before[-1] if before else None
        rows.setdefault((gdate, name), m.group(3))  # first status wins if repeated
    releases.append({
        "file": fn, "stamp_et": stamp(fn).strftime("%Y-%m-%d %H:%M ET"),
        "game_dates_with_rows": sorted({k[0] for k in rows if k[0]}),
        "game_dates_mentioned": sorted({d for _, d in dates}),
        "pdf_sha256": hashlib.sha256(blob).hexdigest(), "pdf_bytes": len(blob),
        "text_chars": len(text), "player_rows": rows,
        "pages_header": re.search(r"Page 1 of (\d+)", text).group(1) if re.search(r"Page 1 of (\d+)", text) else None,
    })
releases.sort(key=lambda r: stamp(r["file"]))

diffs = []
for a, b in zip(releases, releases[1:]):
    overlap = set(a["game_dates_with_rows"]) & set(b["game_dates_with_rows"])
    ra = {k: v for k, v in a["player_rows"].items() if k[0] in overlap}
    rb = {k: v for k, v in b["player_rows"].items() if k[0] in overlap}
    out_scope_a = len(a["player_rows"]) - len(ra)
    out_scope_b = len(b["player_rows"]) - len(rb)
    lbl = lambda k: {"game_date": k[0], "player": k[1]}
    comparable = bool(overlap)  # no shared game date => nothing to diff (not a change)
    changed = [{**lbl(k), "from": ra[k], "to": rb[k]} for k in sorted(ra.keys() & rb.keys(), key=str) if ra[k] != rb[k]] if comparable else []
    added = [{**lbl(k), "status": rb[k]} for k in sorted(rb.keys() - ra.keys(), key=str)] if comparable else []
    removed = [{**lbl(k), "status": ra[k]} for k in sorted(ra.keys() - rb.keys(), key=str)] if comparable else []
    diffs.append({
        "from": a["file"], "from_stamp_et": a["stamp_et"],
        "to": b["file"], "to_stamp_et": b["stamp_et"],
        "overlapping_game_dates": sorted(overlap),
        "comparable": comparable,
        "rows_compared": {"from": len(ra), "to": len(rb)},
        "rows_outside_overlap_not_compared": {"from": out_scope_a, "to": out_scope_b},
        "counts": ({"status_changed": len(changed), "added": len(added), "removed": len(removed),
                   "unchanged": len(ra.keys() & rb.keys()) - len(changed)} if comparable else None),
        "status_changed": changed, "added": added, "removed": removed,
    })

out = {
    "schema": "nba2.injury-diff.session-95053469.v1",
    "session": "arena/95053469-nba2",
    "method": "analysis/session-95053469-injury-diff.py",
    "key": "(game date, player name); matchup/team not reliably recoverable from flattened PDF text",
    "releases": [{k: v for k, v in r.items() if k != "player_rows"} | {"player_rows": len(r["player_rows"])} for r in releases],
    "consecutive_diffs": diffs,
}
open(os.path.join(ROOT, "analysis/session-95053469-injury-diff.json"), "w").write(json.dumps(out, indent=1))
print("releases", len(releases), "pairs", len(diffs))
for d in diffs:
    print(d["from_stamp_et"], "->", d["to_stamp_et"], d["overlapping_game_dates"], d["rows_compared"], d["counts"])
# cross-check: committed transcript-based delta for 11-15 06:15 AM -> PM (capture_2026-11-15)
cap = json.load(open(os.path.join(ROOT, "data/raw/capture_2026-11-15/injury_delta_0615AM_to_0615PM.json")))
cap_changes = {(c["player"]) : (c["from_status"], c["to_status"]) for c in cap["status_changes"]}
mine = [d for d in diffs if d["from"].startswith("Injury-Report_2026-11-15_06_15AM")][0]
mine_changes = {c["player"]: (c["from"], c["to"]) for c in mine["status_changed"]}
cross = {
  "capture_file": "data/raw/capture_2026-11-15/injury_delta_0615AM_to_0615PM.json",
  "capture_status_changes": len(cap_changes), "pdf_regex_status_changes": len(mine_changes),
  "both": sorted(set(cap_changes) & set(mine_changes)) ,
  "only_in_capture_transcript": sorted(set(cap_changes) - set(mine_changes)),
  "only_in_pdf_regex": sorted(set(mine_changes) - set(cap_changes)),
  "note": "capture keys on (matchup, team, player); this diff keys on (game date, player); unresolved disagreements are flagged, not reconciled by hand",
}
out["cross_check_2026-11-15_0615AM_PM"] = cross
open(os.path.join(ROOT, "analysis/session-95053469-injury-diff.json"), "w").write(json.dumps(out, indent=1))
print("cross-check", {k: (len(v) if isinstance(v, list) else v) for k, v in cross.items() if k != "note"})
