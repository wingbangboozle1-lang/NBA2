SEVERITY_BADGE = {"gap": "bad", "info": "info", "blocker": "warn"}


def build_section() -> str:
    rows = []
    for fid, sev, url, wrong, instead, where in sorted(FLAGS):
        rows.append([
            f'<b id="{esc(fid)}">{esc(fid)}</b>',
            badge(sev, SEVERITY_BADGE.get(sev, "info")),
            link(url, "official source", url) if url.startswith("https://www.nba.com")
            or "nba.com" in url else link(url, "source", url),
            wrong, instead,
            gh(where) if "/" in where else f"<code>{esc(where)}</code>",
        ])
    body = note(
        "Added 2026-11-17 by session <code>arena/f5ac4e74-nba2</code> (tasks K-01…K-08). "
        "These are appended to v2's own flag register; nothing above was removed or "
        "reordered. None of them blocks the merge — that is the point of a flag — and every "
        "one names the official document a reviewer would open to check it.", "warn")
    body += table(["ID", "Severity", "Official source", "What is wrong",
                   "What is published instead", "Where to check"],
                  rows,
                  caption=f"{len(FLAGS)} findings from this session's line-by-line pass.")
    return (f'\n<section id="v6-flags">\n<h2>Flagged by the 2026-11-17 measurement pass '
            f'(v6)</h2>\n{body}\n</section>\n')


def append_to_flagged() -> bool:
    p = SITE / "flagged.html"
    if not p.exists():
        return False
    doc = p.read_text()
    if MARKER in doc:
        return False
    section = build_section()
    if "</main>" in doc:
        doc = doc.replace("</main>", section + "</main>", 1)
    else:
        doc = doc.replace("</body>", section + "</body>", 1)
    p.write_text(doc)
    return True


def write_data() -> None:
    V6.mkdir(parents=True, exist_ok=True)
    (V6 / "flags.json").write_text(json.dumps({
        "schema": "nba2.v6.flags.v1",
        "session": "arena/f5ac4e74-nba2",
        "n_flags": len(FLAGS),
        "published_on": "site/flagged.html (appended to v2's register)",
        "flags": [{"id": f[0], "severity": f[1], "official_source": f[2],
                   "what_is_wrong": f[3], "what_is_published": f[4], "where_to_check": f[5]}
                  for f in FLAGS],
    }, indent=1, ensure_ascii=False) + "\n")
